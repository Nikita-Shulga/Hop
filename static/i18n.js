var LANGS = ['en', 'ru'];
var NAMES = { en: 'English', ru: 'Русский' };
var lang = 'en';
var pluralRules = {};
var exact = null;

function norm(l) { return LANGS.indexOf(l) >= 0 ? l : 'en'; }

function pluralForm(n) {
  try {
    if (root.Intl && Intl.PluralRules) return (pluralRules[lang] || (pluralRules[lang] = new Intl.PluralRules(lang))).select(n);
  } catch (e) {}
  if (lang === 'ru') {
    if (n % 1) return 'other';
    var a = Math.abs(n) % 10, b = Math.abs(n) % 100;
    return a === 1 && b !== 11 ? 'one' : a >= 2 && a <= 4 && (b < 12 || b > 14) ? 'few' : 'many';
  }
  return n === 1 ? 'one' : 'other';
}

// Numbers in text: English keeps the plain digits it always showed; Russian uses Russian separators.
function num(n, opts, l) {
  if ((l || lang) === 'en') return String(n);
  try { return Number(n).toLocaleString('ru-RU', opts); } catch (e) { return String(n).replace('.', ','); }
}

function fill(s, vars, esc, l) {
  return s.replace(/\{(\w+)\}/g, function (m, k) {
    if (!vars || vars[k] == null) return m;
    var v = typeof vars[k] === 'number' ? num(vars[k], null, l) : String(vars[k]);
    return esc ? escapeHtml(v) : v;
  });
}

function lookup(key, l) {
  var d = STRINGS[l || lang];
  return d && d[key] != null ? d[key] : STRINGS.en[key];
}

function pick(s, vars, l) {
  if (s && typeof s === 'object') {
    var n = vars && typeof vars.n === 'number' ? vars.n : 0;
    s = s[(l || lang) === 'en' ? (n === 1 ? 'one' : 'other') : pluralForm(n)] || s.other;
  }
  return s;
}

/* t('v.fileCount', {n: 3}) → "3 files" / «3 файла» */
function t(key, vars) {
  var s = pick(lookup(key), vars);
  return s == null ? key : fill(s, vars, false);
}
/* The same, for strings with markup (<b>, <strong>): values are escaped. */
function html(key, vars) {
  var s = pick(lookup(key), vars);
  return s == null ? key : fill(s, vars, true);
}
/* Always English: the canonical text of a msg.* message (what hosts send, and what message() translates). */
function en(key, vars) {
  var s = pick(STRINGS.en[key], vars, 'en');
  return s == null ? key : fill(s, vars, false, 'en');
}

function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]; });
}

/* A message a host or the connection server sent (always English) → the chosen language. Unknown
   messages are shown as they are. */
function message(s) {
  s = s == null ? '' : String(s);
  if (lang === 'en' || !s) return s;
  if (!exact) {
    exact = {};
    Object.keys(STRINGS.en).forEach(function (k) {
      var v = STRINGS.en[k];
      if (k.indexOf('msg.') === 0 && typeof v === 'string' && v.indexOf('{') < 0) exact[v] = k;
    });
  }
  if (exact[s]) return t(exact[s]);
  for (var i = 0; i < PATTERNS.length; i++) {
    var m = s.match(new RegExp(PATTERNS[i][0]));
    if (!m) continue;
    var vars = {};
    PATTERNS[i][2].forEach(function (name, j) { vars[name] = name === 'n' ? Number(m[j + 1]) : message(m[j + 1]); });
    return t(PATTERNS[i][1], vars);
  }
  return s;
}

/* Fill every element marked with data-i18n (text), data-i18n-html (markup), data-i18n-title,
   data-i18n-aria (aria-label) or data-i18n-ph (placeholder) under `scope`. */
function apply(scope, vars) {
  scope = scope || document;
  var each = function (attr, fn) {
    Array.prototype.forEach.call(scope.querySelectorAll('[' + attr + ']'), function (el) { fn(el, el.getAttribute(attr)); });
  };
  each('data-i18n', function (el, k) { var v = t(k, vars); if (el.textContent !== v) el.textContent = v; });
  each('data-i18n-html', function (el, k) { var v = html(k, vars); if (el.innerHTML !== v) el.innerHTML = v; });
  each('data-i18n-title', function (el, k) { el.title = t(k, vars); });
  each('data-i18n-aria', function (el, k) { el.setAttribute('aria-label', t(k, vars)); });
  each('data-i18n-ph', function (el, k) { el.setAttribute('placeholder', t(k, vars)); });
}

function setLang(l) {
  lang = norm(l);
  try { document.documentElement.lang = lang; } catch (e) {}
  return lang;
}

root.HopI18n = {
  langs: LANGS.slice(),
  names: NAMES,
  norm: norm,
  lang: function () { return lang; },
  setLang: setLang,
  t: t,
  html: html,
  en: en,
  num: num,
  message: message,
  apply: apply,
  escape: escapeHtml
};
